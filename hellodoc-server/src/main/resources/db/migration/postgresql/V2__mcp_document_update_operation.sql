CREATE TABLE IF NOT EXISTS mcp_document_update_operation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    doc_id BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    input_hash VARCHAR(64) NOT NULL,
    result_version INTEGER NOT NULL,
    result_updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT mcp_document_update_operation_unique UNIQUE (user_id, doc_id, request_id)
);
DO $$ BEGIN
    IF to_regclass('public.kb_document') IS NOT NULL AND NOT EXISTS
        (SELECT 1 FROM pg_constraint WHERE conname = 'mcp_document_update_doc_fk' AND conrelid = 'mcp_document_update_operation'::regclass) THEN
        ALTER TABLE mcp_document_update_operation ADD CONSTRAINT mcp_document_update_doc_fk
            FOREIGN KEY (doc_id) REFERENCES kb_document(id) ON DELETE CASCADE;
    END IF;
END $$;
